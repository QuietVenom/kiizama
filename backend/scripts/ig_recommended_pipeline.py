async def run_discovery_phase(
    *,
    options: ScriptOptions,
    export_rows: list[dict[str, str]],
    export_csv_path: Path,
    recommended_rows: list[dict[str, str]],
    recommended_csv_path: Path,
) -> dict[str, int]:
    counters = {
        "requested": 0,
        "successful": 0,
        "failed": 0,
        "not_found": 0,
        "skipped_existing": 0,
        "added_recommended": 0,
    }
    pending_usernames = [
        normalize_username(row.get("username"))
        for row in export_rows
        if row_is_processable(row, retry_failed=options.retry_failed)
        and normalize_username(row.get("username"))
    ]
    row_by_username = {
        normalize_username(row.get("username")): row
        for row in export_rows
        if normalize_username(row.get("username"))
    }

    for batch in chunked(pending_usernames, options.batch_size):
        counters["requested"] += len(batch)
        response = await run_runner_response(options=options, usernames=batch)
        processed_at = utcnow().isoformat()
        recommended_candidates = [
            normalize_username(user.username)
            for username in batch
            if (result := response.results.get(username)) is not None and result.success
            for user in result.recommended_users
            if normalize_username(user.username)
        ]
        existing_profile_usernames = get_existing_profile_usernames(
            recommended_candidates
        )
        counters["skipped_existing"] += len(existing_profile_usernames)

        for username in batch:
            row = row_by_username[username]
            result = response.results.get(username)
            if result is None:
                row["status"] = "failed"
                row["processed_at"] = processed_at
                row["error"] = response.error or "Missing scrape result"
                counters["failed"] += 1
                continue

            row["processed_at"] = processed_at
            if result.success:
                row["status"] = "done"
                row["error"] = ""
                counters["successful"] += 1
                counters["added_recommended"] += upsert_recommended_rows(
                    recommended_rows,
                    source_username=username,
                    recommended_usernames=[
                        user.username or ""
                        for user in result.recommended_users
                        if normalize_username(user.username)
                        not in existing_profile_usernames
                    ],
                    discovered_at=processed_at,
                )
            elif result.error == NOT_FOUND_ERROR:
                row["status"] = "not_found"
                row["error"] = result.error or ""
                counters["not_found"] += 1
            else:
                row["status"] = "failed"
                row["error"] = result.error or response.error or "Scrape failed"
                counters["failed"] += 1

        write_csv_rows(export_csv_path, EXPORT_HEADERS, export_rows)
        write_csv_rows(recommended_csv_path, RECOMMENDED_HEADERS, recommended_rows)

    return counters


async def run_persistence_phase(
    *,
    options: ScriptOptions,
    recommended_rows: list[dict[str, str]],
    recommended_csv_path: Path,
) -> tuple[dict[str, int], list[str], list[str], list[str]]:
    counters = {"requested": 0, "successful": 0, "failed": 0, "not_found": 0}
    persisted_usernames: list[str] = []
    not_found_usernames: list[str] = []
    failed_usernames: list[str] = []
    pending_usernames = [
        normalize_username(row.get("username"))
        for row in recommended_rows
        if row_is_processable(row, retry_failed=options.retry_failed)
        and normalize_username(row.get("username"))
    ]
    row_by_username = {
        normalize_username(row.get("username")): row
        for row in recommended_rows
        if normalize_username(row.get("username"))
    }

    for batch in chunked(pending_usernames, options.batch_size):
        counters["requested"] += len(batch)
        response = await run_runner_response(options=options, usernames=batch)
        if not options.skip_ai:
            response = await enrich_with_ai_analysis(
                response,
                analysis_service=BackendInstagramProfileAnalysisServiceV2(),
            )

        with Session(engine) as session:
            response = await persist_scrape_results_to_db(
                response,
                persistence=build_persistence(session),
            )

        processed_at = utcnow().isoformat()
        for username in batch:
            row = row_by_username[username]
            result = response.results.get(username)
            row["processed_at"] = processed_at
            if result is None:
                row["status"] = "failed"
                row["error"] = response.error or "Missing scrape result"
                failed_usernames.append(username)
                counters["failed"] += 1
                continue

            if result.success:
                row["status"] = "done"
                row["error"] = ""
                persisted_usernames.append(username)
                counters["successful"] += 1
            elif result.error == NOT_FOUND_ERROR:
                row["status"] = "not_found"
                row["error"] = result.error or ""
                not_found_usernames.append(username)
                counters["not_found"] += 1
            else:
                row["status"] = "failed"
                row["error"] = result.error or response.error or "Scrape failed"
                failed_usernames.append(username)
                counters["failed"] += 1

        write_csv_rows(recommended_csv_path, RECOMMENDED_HEADERS, recommended_rows)

    return counters, persisted_usernames, not_found_usernames, failed_usernames


async def discover_recommended(options: ScriptOptions) -> DiscoverRecommendedOutput:
    if options.input_csv is None:
        raise ValueError("--input-csv is required for --discover-recommended.")

    configure_runtime_secrets_from_settings()
    ping_postgres()

    input_csv_path = options.input_csv
    recommended_csv_path = resolve_recommended_csv_path(options)
    ensure_parent_dir(recommended_csv_path)
    if not input_csv_path.exists():
        raise FileNotFoundError(f"Input CSV not found: {input_csv_path}")

    export_rows = load_csv_rows(input_csv_path, EXPORT_HEADERS)
    recommended_rows = load_csv_rows(recommended_csv_path, RECOMMENDED_HEADERS)
    if not recommended_csv_path.exists():
        write_csv_rows(recommended_csv_path, RECOMMENDED_HEADERS, recommended_rows)

    discovery_counters = await run_discovery_phase(
        options=options,
        export_rows=export_rows,
        export_csv_path=input_csv_path,
        recommended_rows=recommended_rows,
        recommended_csv_path=recommended_csv_path,
    )

    return DiscoverRecommendedOutput(
        success=discovery_counters["failed"] == 0,
        input_csv=str(input_csv_path),
        recommended_csv=str(recommended_csv_path),
        discovery_counters=discovery_counters,
        discovered_count=len(recommended_rows),
        skipped_existing_count=discovery_counters["skipped_existing"],
        error=None,
    )


async def persist_recommended(options: ScriptOptions) -> PersistRecommendedOutput:
    if options.recommended_csv is None:
        raise ValueError("--recommended-csv is required for --persist-recommended.")

    configure_runtime_secrets_from_settings()
    ping_postgres()

    recommended_csv_path = options.recommended_csv
    if not recommended_csv_path.exists():
        raise FileNotFoundError(f"Recommended CSV not found: {recommended_csv_path}")

    recommended_rows = load_csv_rows(recommended_csv_path, RECOMMENDED_HEADERS)
    (
        persistence_counters,
        persisted_usernames,
        not_found_usernames,
        failed_usernames,
    ) = await run_persistence_phase(
        options=options,
        recommended_rows=recommended_rows,
        recommended_csv_path=recommended_csv_path,
    )

    return PersistRecommendedOutput(
        success=persistence_counters["failed"] == 0,
        recommended_csv=str(recommended_csv_path),
        persistence_counters=persistence_counters,
        persisted_usernames=persisted_usernames,
        not_found_usernames=not_found_usernames,
        failed_usernames=failed_usernames,
        error=None,
    )


async def run(options: ScriptOptions) -> RunOutput:
    if options.mode == "export_profiles":
        return export_profiles_to_csv(options)
    if options.mode == "discover_recommended":
        return await discover_recommended(options)
    return await persist_recommended(options)


def print_output(output: RunOutput, *, json_output: bool) -> None:
    payload = asdict(output)
    if json_output:
        sys.stdout.write(f"{json.dumps(payload, sort_keys=True)}\n")
        return

    for key, value in payload.items():
        sys.stdout.write(f"{key}: {value}\n")


def _is_config_error(exc: Exception) -> bool:
    return isinstance(
        exc,
        (
            FileNotFoundError,
            ValueError,
            ValidationError,
            SQLAlchemyError,
            RuntimeError,
        ),
    )


def _json_requested(argv: list[str] | None) -> bool:
    args = argv if argv is not None else sys.argv[1:]
    return "--json" in args


def main(argv: list[str] | None = None) -> int:
    logging.basicConfig(level=logging.INFO, stream=sys.stderr)
    try:
        options = parse_args(argv)
        output = asyncio.run(run(options))
        print_output(output, json_output=options.json_output)
        return EXIT_SUCCESS if output.success else EXIT_SCRAPE_FAILED
    except KeyboardInterrupt:
        return EXIT_INTERRUPTED
    except SystemExit:
        raise
    except Exception as exc:
        if _is_config_error(exc):
            output = ExportOutput(
                success=False,
                path="",
                exported_count=0,
                error=str(exc),
            )
            print_output(output, json_output=_json_requested(argv))
            return EXIT_CONFIG_ERROR
        raise


if __name__ == "__main__":
    raise SystemExit(main())
