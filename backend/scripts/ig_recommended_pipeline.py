def ensure_parent_dir(path: Path) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)


def normalize_username(value: str | None) -> str:
    return (value or "").strip().strip("@").strip("/").lower()


def normalize_sources(value: str | None) -> list[str]:
    sources: list[str] = []
    seen: set[str] = set()
    for raw_source in (value or "").split("|"):
        source = normalize_username(raw_source)
        if not source or source in seen:
            continue
        seen.add(source)
        sources.append(source)
    return sources


def join_sources(sources: Iterable[str]) -> str:
    normalized = []
    seen: set[str] = set()
    for source in sources:
        username = normalize_username(source)
        if not username or username in seen:
            continue
        seen.add(username)
        normalized.append(username)
    return "|".join(normalized)


def chunked(items: Sequence[str], size: int) -> Iterable[list[str]]:
    for start in range(0, len(items), size):
        yield list(items[start : start + size])


def row_is_processable(row: dict[str, str], *, retry_failed: bool) -> bool:
    statuses = RETRYABLE_STATUSES if retry_failed else ACTIVE_STATUSES
    return row.get("status", "pending") in statuses


def load_csv_rows(path: Path, headers: Sequence[str]) -> list[dict[str, str]]:
    if not path.exists():
        return []
    with path.open(newline="", encoding="utf-8") as file:
        reader = csv.DictReader(file)
        rows: list[dict[str, str]] = []
        for raw_row in reader:
            row = {header: (raw_row.get(header) or "") for header in headers}
            rows.append(row)
        return rows


def write_csv_rows(
    path: Path,
    headers: Sequence[str],
    rows: Sequence[dict[str, str]],
) -> None:
    ensure_parent_dir(path)
    with NamedTemporaryFile(
        "w",
        newline="",
        encoding="utf-8",
        dir=path.parent,
        prefix=f".{path.name}.",
        delete=False,
    ) as temp_file:
        writer = csv.DictWriter(temp_file, fieldnames=list(headers))
        writer.writeheader()
        for row in rows:
            writer.writerow({header: row.get(header, "") for header in headers})
        temp_path = Path(temp_file.name)
    temp_path.replace(path)


def upsert_recommended_rows(
    rows: list[dict[str, str]],
    *,
    source_username: str,
    recommended_usernames: Iterable[str],
    discovered_at: str,
) -> int:
    by_username = {
        normalize_username(row.get("username")): row
        for row in rows
        if normalize_username(row.get("username"))
    }
    added_count = 0
    source = normalize_username(source_username)

    for raw_username in recommended_usernames:
        username = normalize_username(raw_username)
        if not username:
            continue
        existing = by_username.get(username)
        if existing is None:
            row = {
                "username": username,
                "source_usernames": source,
                "status": "pending",
                "discovered_at": discovered_at,
                "processed_at": "",
                "error": "",
            }
            rows.append(row)
            by_username[username] = row
            added_count += 1
            continue

        sources = normalize_sources(existing.get("source_usernames"))
        if source and source not in sources:
            sources.append(source)
            existing["source_usernames"] = join_sources(sources)
        if not existing.get("discovered_at"):
            existing["discovered_at"] = discovered_at
        if not existing.get("status"):
            existing["status"] = "pending"

    return added_count


def get_existing_profile_usernames(usernames: Iterable[str]) -> set[str]:
    normalized_usernames = sorted(
        {normalize_username(username) for username in usernames if username}
    )
    if not normalized_usernames:
        return set()

    username_column = cast(Any, IgProfile.username)
    with Session(engine) as session:
        existing = session.exec(
            select(IgProfile.username).where(username_column.in_(normalized_usernames))
        ).all()
    return {normalize_username(username) for username in existing}


def build_export_statement(options: ScriptOptions) -> Any:
    updated_at = cast(Any, IgProfile.updated_at)
    username = cast(Any, IgProfile.username)
    statement = select(IgProfile.username, IgProfile.updated_at)

    if options.updated_after is not None:
        statement = statement.where(updated_at >= options.updated_after)
    if options.updated_before is not None:
        statement = statement.where(updated_at <= options.updated_before)

    if options.oldest is not None:
        statement = statement.order_by(updated_at.asc(), username.asc()).limit(
            options.oldest
        )
    elif options.newest is not None:
        statement = statement.order_by(updated_at.desc(), username.asc()).limit(
            options.newest
        )
    else:
        statement = statement.order_by(username.asc())
    return statement


def export_profiles_to_csv(options: ScriptOptions) -> ExportOutput:
    output_path = resolve_export_csv_path(options)
    ensure_parent_dir(output_path)
    ping_postgres()

    with Session(engine) as session:
        records = session.exec(build_export_statement(options)).all()

    rows = [
        {
            "username": normalize_username(record[0]),
            "updated_at": record[1].astimezone(UTC).isoformat()
            if record[1].tzinfo
            else record[1].replace(tzinfo=UTC).isoformat(),
            "status": "pending",
            "processed_at": "",
            "error": "",
        }
        for record in records
        if normalize_username(record[0])
    ]
    write_csv_rows(output_path, EXPORT_HEADERS, rows)
    return ExportOutput(
        success=True,
        path=str(output_path),
        exported_count=len(rows),
    )


